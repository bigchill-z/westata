"""E3 conformance for the P6/P7 models, driven by captured Stata output.

Reference values transcribed from
``stata_fixtures/p6p7_outputs.txt`` (StataNow 19.5, generated by
``scripts/capture_p6p7_fixtures.py``):

==========  ==========================================================
command     Stata
==========  ==========================================================
truncreg    x1 1.568894, x2 -.5033393, _cons .9280214, /sigma .8153158
intreg      x1 1.197311, _cons 1.94128, /lnsigma -.0827015
heckman     x 1.965111, _cons 1.026726, z .8021853, rho .2849988,
            lambda .2861034, /athrho .2931144
zip         x1 .559456, _cons .4039659, inflate x1 .0033665,
            inflate _cons -1.016455
zinb        (converged; values captured in the fixture file)
ztp         x1 .5415945, _cons .4189287
tnbreg      x1 .6035713
==========  ==========================================================

The module skips cleanly when a model has not been wired into the public API
yet, so it can land before the implementations do.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import westata as ws

FIXTURES = Path(__file__).resolve().parent / "stata_fixtures"
REFERENCE = FIXTURES / "p6p7_outputs.txt"

if not REFERENCE.exists():
    pytest.skip("P6/P7 fixtures missing", allow_module_level=True)


def _require(name: str):
    """Return the westata class, or skip when it is not wired yet."""

    attribute = getattr(ws, name, None)
    if attribute is None:
        pytest.skip(f"{name} is not exposed on westata yet")
    return attribute


# --------------------------------------------------------------- data


def truncated_frame(n: int = 800, seed: int = 31) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    x1 = rng.normal(size=n)
    x2 = rng.normal(size=n)
    latent = 1.0 + 1.5 * x1 - 0.5 * x2 + rng.normal(scale=0.8, size=n)
    keep = latent > 0.0
    return pd.DataFrame({"y": latent[keep], "x1": x1[keep], "x2": x2[keep]})


def interval_frame(n: int = 600, seed: int = 37) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    x1 = rng.normal(size=n)
    latent = 2.0 + 1.2 * x1 + rng.normal(scale=0.9, size=n)
    edges = np.array([-np.inf, 0.5, 1.5, 2.5, 3.5, np.inf])
    index = np.searchsorted(edges, latent, side="right") - 1
    return pd.DataFrame({"lo": edges[index], "hi": edges[index + 1], "x1": x1})


def selection_frame(n: int = 1500, seed: int = 41) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    z = rng.normal(size=n)
    x = rng.normal(size=n)
    common = rng.normal(size=n)
    u = 0.6 * common + 0.8 * rng.normal(size=n)
    e = 0.6 * common + 0.8 * rng.normal(size=n)
    selected = (0.8 * z + u) > 0
    outcome = 1.0 + 2.0 * x + e
    return pd.DataFrame(
        {
            "y": np.where(selected, outcome, np.nan),
            "x": x,
            "z": z,
            "selected": selected.astype(float),
        }
    )


def count_frame(n: int = 1200, seed: int = 43) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    x1 = rng.normal(size=n)
    mu = np.exp(0.4 + 0.6 * x1)
    structural_zero = rng.random(size=n) < 0.25
    counts = np.where(structural_zero, 0, rng.poisson(mu)).astype(float)
    return pd.DataFrame({"y": counts, "x1": x1})


def overdispersed_frame(n: int = 1200, seed: int = 47) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    x1 = rng.normal(size=n)
    mu = np.exp(0.4 + 0.6 * x1)
    lam = rng.gamma(shape=1.0 / 0.5, scale=mu * 0.5)
    return pd.DataFrame({"y": rng.poisson(lam).astype(float), "x1": x1})


# ------------------------------------------------------------ truncreg


def test_truncreg_matches_stata():
    Truncreg = _require("Truncreg")
    frame = truncated_frame()
    result = Truncreg.from_formula("y ~ x1 + x2", frame, lower=0.0).fit()

    params = result.params
    assert float(params["x1"]) == pytest.approx(1.568894, rel=1e-4)
    assert float(params["x2"]) == pytest.approx(-0.5033393, rel=1e-4)
    assert float(params["Intercept"]) == pytest.approx(0.9280214, rel=1e-4)
    assert float(result.e["sigma"]) == pytest.approx(0.8153158, rel=1e-4)


# -------------------------------------------------------------- intreg


def test_intreg_matches_stata():
    Intreg = _require("Intreg")
    frame = interval_frame()
    result = Intreg.from_formula("lo hi ~ x1", frame).fit()

    assert float(result.params["x1"]) == pytest.approx(1.197311, rel=1e-4)
    assert float(result.params["Intercept"]) == pytest.approx(1.94128, rel=1e-4)


# ------------------------------------------------------------- heckman


def test_heckman_twostep_recovers_stata_coefficients():
    Heckman = _require("Heckman")
    frame = selection_frame()
    result = Heckman.from_formula("y ~ x + select(selected ~ z)", frame).fit(
        method="twostep"
    )

    params = result.params
    # Stata: main equation x 1.965111, _cons 1.026726; selection z .8021853.
    assert float(params["x"]) == pytest.approx(1.965111, rel=5e-2)
    names = list(params.index)
    assert any("z" in name for name in names), names
    z_terms = [value for name, value in params.items() if name.endswith("z")]
    assert z_terms and float(z_terms[0]) == pytest.approx(0.8021853, rel=5e-2)


def test_heckman_reports_rho_and_lambda():
    Heckman = _require("Heckman")
    result = Heckman.from_formula(
        "y ~ x + select(selected ~ z)", selection_frame()
    ).fit(method="twostep")

    # Stata: rho .2849988, sigma 1.003876, lambda .2861034.
    assert "rho" in result.e
    assert "sigma" in result.e
    assert float(result.e["rho"]) == pytest.approx(0.2849988, abs=0.1)


def test_heckman_ml_is_refused():
    Heckman = _require("Heckman")
    model = Heckman.from_formula("y ~ x + select(selected ~ z)", selection_frame())
    with pytest.raises(Exception):
        model.fit(method="ml")


# ----------------------------------------------------------- zero-inflated


def test_zip_matches_stata():
    ZeroInflatedPoisson = _require("ZeroInflatedPoisson")
    frame = count_frame()
    result = ZeroInflatedPoisson.from_formula("y ~ x1", frame, inflate="x1").fit()

    # Stata: main x1 .559456, _cons .4039659; inflate x1 .0033665,
    # inflate _cons -1.016455.
    params = result.params
    labels = list(params.index)
    assert any(label.startswith("x1") for label in labels), labels
    count_values = {label: float(value) for label, value in params.items()}
    main = next(value for label, value in count_values.items() if "inflate" not in label)
    assert main == pytest.approx(0.559456, rel=5e-2)


def test_zinb_runs_and_produces_finite_parameters():
    ZeroInflatedNegativeBinomial = _require("ZeroInflatedNegativeBinomial")
    frame = overdispersed_frame()
    result = ZeroInflatedNegativeBinomial.from_formula(
        "y ~ x1", frame, inflate="_cons"
    ).fit()
    assert np.all(np.isfinite(result.params.to_numpy()))


# ----------------------------------------------------------- truncated counts


def test_ztp_matches_stata():
    TruncatedPoisson = _require("TruncatedPoisson")
    frame = count_frame().query("y > 0").reset_index(drop=True)
    result = TruncatedPoisson.from_formula("y ~ x1", frame, lower=1).fit()

    # Stata: x1 .5415945, _cons .4189287.
    assert float(result.params["x1"]) == pytest.approx(0.5415945, rel=5e-2)


def test_tnbreg_matches_stata():
    TruncatedNegativeBinomial = _require("TruncatedNegativeBinomial")
    frame = overdispersed_frame().query("y > 0").reset_index(drop=True)
    result = TruncatedNegativeBinomial.from_formula("y ~ x1", frame, lower=1).fit()

    # Stata: x1 .6035713.
    assert float(result.params["x1"]) == pytest.approx(0.6035713, rel=5e-2)
