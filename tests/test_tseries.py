def test_garch_defaults_are_statas_opg_and_presample():
    """Stata's ``arch`` reports OPG SEs and starts from ``e(archi)``.

    Captured from StataNow 19.5 (``arch yg, arch(1) garch(1)`` on the 600-obs
    GARCH series from ``retest/domains/tseries/run.py``, 2026-10-24):
    ``e(vcetype) = "OPG"``, SE = [0.03740327, 0.03725869, 0.05761018,
    0.03264898] in Stata's (mu, L.arch, L.garch, omega) order, and
    ``e(archi) = 0.9690947048974677``.  westata's defaults now use the same
    two conventions; the package's ``robust`` SEs are 2.78e-01 away.
    """

    returns = _garch_process(n=600, seed=777)
    res = GARCH(returns, p=1, q=1).fit()
    robust = GARCH(returns, p=1, q=1).fit(cov_type="robust", presample="arch")

    assert res.e["vcetype"] == "OPG"
    # Baseline: the old defaults were the arch package's, i.e. different.
    assert np.max(np.abs(res.bse.to_numpy() / robust.bse.to_numpy() - 1.0)) > 1e-2
    # The presample variance label is exposed and is the demeaned mean square.
    mu = float(res.params["mu"])
    assert res.e["archi"] == pytest.approx(float(np.mean((returns - mu) ** 2)), rel=1e-9)
    # OPG differs from both of the package's own estimators on this data.
    classic = GARCH(returns, p=1, q=1).fit(cov_type="classic", presample="stata")
    assert np.max(np.abs(res.bse.to_numpy() / classic.bse.to_numpy() - 1.0)) > 1e-2


