def test_johansen_on_cointegrated_series():
    rng = np.random.default_rng(9)
    n = 400
    random_walk = np.cumsum(rng.normal(size=n))
    # A second series cointegrated with the first.
    other = random_walk + rng.normal(scale=0.2, size=n)
    data = np.column_stack([random_walk, other])

    outcome = VECM(data, coint_rank=1).johansen(k_ar_diff=1)
    frame = outcome.to_frame()
    assert frame.shape[0] >= 1
    # The first null (r=0 against r>=1) should be rejected for cointegrated data.
    assert frame.iloc[0]["trace"] > frame.iloc[0]["trace_5pct"]


def test_johansen_uses_stat_critical_values_for_the_constant_case():
    """``vecrank`` hard-codes Johansen's tables; statsmodels returns Osterwald-Lenum.

    Captured from StataNow 19.5 (``vecrank yc1 yc2, lags(2) trend(constant) max``,
    2026-10-24): the 5% trace critical value at r=1 is **3.76** and the
    max-eigenvalue one at K-r=2 is **14.07**, while statsmodels reports 3.8415
    and 14.2639.  Statistics are unchanged by this repair.
    """

    rng = np.random.default_rng(9)
    n = 400
    random_walk = np.cumsum(rng.normal(size=n))
    other = random_walk + rng.normal(scale=0.2, size=n)
    data = np.column_stack([random_walk, other])

    outcome = VECM(data, coint_rank=1).johansen(k_ar_diff=1, det_order=0)
    # Rows are the tests of r = 0, 1; columns are [90%, 95%, 99%].
    assert outcome.trace_critical[1, 1] == pytest.approx(3.76, abs=1e-12)
    assert outcome.trace_critical[0, 1] == pytest.approx(15.41, abs=1e-12)
    assert outcome.maxeig_critical[0, 1] == pytest.approx(14.07, abs=1e-12)
    assert outcome.maxeig_critical[1, 1] == pytest.approx(3.76, abs=1e-12)
    # The 90% column is not tabulated by Stata's ado.
    assert np.isnan(outcome.trace_critical[0, 0])
    assert outcome.trace_critical[0, 2] == pytest.approx(20.04, abs=1e-12)


def test_select_rank_returns_the_rank_and_refuses_untabulated_levels():
    """``select_rank`` returns ``r`` itself, uses the 5% column by default.

    Row ``i`` tests ``r = i`` and the default level is 0.05 -- the same rule
    ``vecrank``'s ``*`` marker applies.  A 10% level is refused because
    ``_vecgetcv.ado`` tabulates only 95% and 99%; returning statsmodels' 90%
    value would mix two tables in one decision.
    """

    rng = np.random.default_rng(9)
    n = 400
    random_walk = np.cumsum(rng.normal(size=n))
    other = random_walk + rng.normal(scale=0.2, size=n)
    data = np.column_stack([random_walk, other])
    outcome = VECM(data, coint_rank=1).johansen(k_ar_diff=1, det_order=0)

    assert outcome.select_rank() == outcome.select_rank(level=0.05)
    assert outcome.select_rank() == outcome.select_rank(statistic="trace")
    # The return value is a cointegration rank in [0, K], not an array index.
    assert outcome.select_rank() in {0, 1, 2}
    assert outcome.select_rank(statistic="maxeig") in {0, 1, 2}
    with pytest.raises(ValueError, match="level"):
        outcome.select_rank(level=0.10)


def test_to_stata_table_renders_missing_critical_values_as_none():
    """The display view shows ``None`` where Stata prints blank, numbers elsewhere.

    Stata's ``vecrank`` prints the critical value in the 5% column for every
    rank row, and never prints a 90% column.  ``to_stata_table()`` keeps the
    numeric values of ``to_frame()`` while rendering non-finite entries as
    ``None`` so a printed table does not show ``nan``.  The numeric arrays keep
    ``np.nan``, so this is presentation only.
    """

    rng = np.random.default_rng(9)
    n = 400
    random_walk = np.cumsum(rng.normal(size=n))
    other = random_walk + rng.normal(scale=0.2, size=n)
    data = np.column_stack([random_walk, other])
    outcome = VECM(data, coint_rank=1).johansen(k_ar_diff=1, det_order=0)

    frame = outcome.to_frame()
    rendered = outcome.to_stata_table()
    assert list(rendered.columns) == list(frame.columns)
    # With every 5% value finite, rendering is a no-op and stays numeric.
    assert rendered["trace_5pct"].dtype == np.float64
    assert rendered["maxeig_5pct"].dtype == np.float64
    # Same 5% numbers; only the dtype changes (object, to allow None).
    np.testing.assert_allclose(
        rendered["trace_5pct"].to_numpy(dtype=float),
        frame["trace_5pct"].to_numpy(dtype=float),
        rtol=0,
    )
    np.testing.assert_allclose(
        rendered["maxeig_5pct"].to_numpy(dtype=float),
        frame["maxeig_5pct"].to_numpy(dtype=float),
        rtol=0,
    )
    # A NaN critical value becomes None; a finite one stays a float.
    broken = VECM(data, coint_rank=1).johansen(k_ar_diff=1, det_order=0)
    broken.trace_critical[0, 1] = np.nan
    shown = broken.to_stata_table()["trace_5pct"].tolist()
    assert shown[0] is None
    assert isinstance(shown[1], float)
    # The numeric path keeps float64 and np.nan, so np.isnan still works.
    numeric = broken.to_frame()
    assert numeric["trace_5pct"].dtype == np.float64
    assert np.isnan(numeric["trace_5pct"].to_numpy()[0])


def test_johansen_rank_decision_matches_vecrank_on_borderline_data():
    """A 3.8369 statistic between 3.76 and 3.8415 selects rank 2, like Stata.

    StataNow 19.5, 2026-10-24, ``vecrank yb1 yb2, lags(2) trend(constant)``:
    trace = 95.9056 (cv 15.41) and 3.8369 (cv 3.76) -> rank 2, no "*" on r=1.
    The pair is ``cointegrated_pair(seed=248)`` from
    ``retest/domains/tseries/run.py``.  With Osterwald-Lenum's 3.8415 the same
    data selects rank 1, i.e. the table alone flips the conclusion.
    """

    rng = np.random.default_rng(248)
    n = 300
    shocks = rng.normal(size=(n, 2))
    x = np.cumsum(shocks[:, 0])
    u = np.zeros(n)
    for t in range(1, n):
        u[t] = 0.4 * u[t - 1] + 0.05 * shocks[t, 1]
    data = np.column_stack([2.0 + 1.5 * x + u, x])

    outcome = VECM(data, coint_rank=1).johansen(lags=2, det_order=0)
    assert 3.76 < outcome.trace[1] < 3.8415
    assert outcome.select_rank() == 2
    assert outcome.select_rank(statistic="maxeig") == 2
    # The pre-fix (statsmodels) table would have accepted r=1.
    assert outcome.trace[1] < 3.8415


def test_johansen_trend_specification_adds_the_trend_to_the_regression():
    """``vecrank ..., trend(trend)``: Stata 92.2870, statsmodels 92.3175.

    StataNow 19.5 (``vecrank yc1 yc2, lags(2) trend(trend) max``, 2026-10-24)
    prints trace = 92.2870 and max-eigen = 90.6871.  statsmodels' det_order=1
    detrends but never adds the trend column; with the column the statistic
    matches Stata to the printed precision.
    """

    rng = np.random.default_rng(1)
    n = 300
    shocks = rng.normal(size=(n, 2))
    x = np.cumsum(shocks[:, 0])
    u = np.zeros(n)
    for t in range(1, n):
        u[t] = 0.4 * u[t - 1] + 0.05 * shocks[t, 1]
    data = np.column_stack([2.0 + 1.5 * x + u, x])

    outcome = VECM(data, coint_rank=1).johansen(lags=2, det_order=1)
    assert outcome.trace[0] == pytest.approx(92.2870, rel=5e-5)
    assert outcome.maxeig[0] == pytest.approx(90.6871, rel=5e-5)
    assert outcome.trace_critical[0, 1] == pytest.approx(18.17, abs=1e-12)


