"""The single source of truth for what gets replicated in Autor, Dorn & Hanson (2013).

Both sides of the replication -- the Stata do-file generated by ``gen_do.py`` and the
``westata`` driver in ``run_westata.py`` -- read their specifications from this module
and nothing else.  That is deliberate: a replication that lets the two sides drift
apart in variable lists, weights or clustering produces two numbers that cannot be
compared, and the resulting "difference" says nothing about either implementation.

Layout
------
``SPECS``
    Every estimated model, one row per table column.  Each row carries the dependent
    variable, the endogenous regressor and its instruments (empty for OLS), the
    exogenous controls, the weight type, the clustering variable and the sample
    restriction that the paper's column applies.

``PAPER``
    The numbers the paper prints, transcribed from the published tables.  The source
    of every row is recorded in ``PAPER_SOURCE``.  These exist so the report can
    answer the only question that matters to a reader -- did the replication land on
    the published number? -- rather than merely whether two programs agree with each
    other.

``CONTROLS``
    The named control sets.  The paper's do-file writes ``reg*`` for the nine Census
    division dummies; expanding them explicitly here means a missing dummy is an
    assertion failure instead of a silently shorter regression.
"""

