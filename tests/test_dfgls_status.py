"""dfgls: the diagnostic ado proves the package follows the visible steps, and Stata does not.

Round 122 ran the experiment round 121 designed: a COPY of dfgls.ado with `di` probes inserted at
each step, so the numbers the ado actually sees are visible.

    DEBUG nobs(from sum touse) = 62
    DEBUG alpha =   0.8870967742
    DEBUG e(N) of the GLS reg = 62
    DEBUG _b[iota] =     5.2182086367
    DEBUG dty[1] =  -0.4577453990
    DEBUG dty[2] =  -0.4298838038
    DEBUG e(N) of the ADF reg = 51
    DEBUG _b[L.dty] =     0.0174897143
    DEBUG _se[L.dty] =    0.0216971191
    DEBUG tau =       0.806085

Every value reproduces the package's own arithmetic exactly. And the installed command reports:

    r(results) row 1, column 5  =  -1.2843

So the divergence is NOT in anything this reconstruction covers. It is in behaviour of the real
`dfgls` that neither the source comments, nor a line-for-line copy, nor a traced run shows.

TWO CANDIDATES ELIMINATED this round:

  * the sign convention -- negating dty leaves coef/se unchanged, so 8.06e-1 cannot become
    -1.2843 by a sign flip;
  * cbar = -13.5 (the trended variant) -- gives tau 0.0647 with b_iota 5.443549, further away,
    and the command reports "DF-GLS tau" without trend anyway.

The full-tau comparison also rules out a simple index shift:

    ours   0.8061  0.8980  0.7578  0.6033  0.7438  1.1232  1.1247  1.0793  0.9007  0.7890
    Stata -1.2843 -1.4057 -1.7480 -2.0974 -2.0185 -1.7582 -1.9293 -2.1342 -2.4361 -2.6371

Ours are all positive, Stata's all negative, and the pairwise sums are not constant -- so this is
not a sign, offset, or scaling difference. The two series are generated by different computations.

WHAT REMAINS, recorded rather than guessed: the real ado must call into something the copy does not
replicate -- most plausibly the `GetCritD`/`GetCritE` helper programs, which are invoked between
the detrending and the ADF regression and could re-set the estimation sample or `_b`. The next step
is to trace those helpers, not to re-derive the regression.

Not fixed. A unit-root statistic of the wrong sign is unusable and three prior reconstructions
agree with each other while disagreeing with Stata -- which is evidence the reconstruction itself
is the wrong instrument.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

import westata as ws

DATA = r"D:\myCodeProject\test_westata\data\nelson_plosser.dta"

#: `r(results)` column 5, all ten rows, from a live `dfgls lrgnp`.
STATA_TAU = [-1.2843, -1.4057, -1.7480, -2.0974, -2.0185, -1.7582, -1.9293, -2.1342, -2.4361, -2.6371]

#: What the reconstructed steps produce, and what the package produces.
RECONSTRUCTION_TAU = [0.8061, 0.8980, 0.7578, 0.6033, 0.7438, 1.1232, 1.1247, 1.0793, 0.9007, 0.7890]


@pytest.fixture(scope="module")
def series():
    try:
        frame = pd.read_stata(DATA)
    except FileNotFoundError:  # pragma: no cover - data lives outside the repo
        pytest.skip("nelson_plosser.dta is not available")
    values = np.asarray(frame["lrgnp"], dtype=float)
    return values[np.isfinite(values)]


def test_the_package_reproduces_the_reconstruction(series) -> None:
    """So the package is not where the deviation enters."""

    result = ws.dfgls(series)
    mine = [round(cell.statistic, 4) for cell in result.cells]
    assert mine == pytest.approx(RECONSTRUCTION_TAU, abs=5e-4)


def test_the_two_series_are_not_a_sign_or_offset_apart(series) -> None:
    """Which rules out the two cheap explanations for a wrong unit-root statistic."""

    result = ws.dfgls(series)
    mine = [cell.statistic for cell in result.cells]
    # Every one of ours is positive and every Stata value negative.
    assert all(value > 0 for value in mine)
    assert all(value < 0 for value in STATA_TAU)
    # And the pairwise differences are not constant, so it is not an offset either.
    differences = [a - b for a, b in zip(mine, STATA_TAU)]
    assert max(differences) - min(differences) > 0.5


def test_the_sample_and_table_shape_are_correct(series) -> None:
    """These parts are verified and should not be disturbed by a future fix."""

    result = ws.dfgls(series)
    assert [cell.lags for cell in result.cells] == list(range(10, 0, -1))
    assert all(cell.nobs == 51 for cell in result.cells)
    assert len(series) == 62
