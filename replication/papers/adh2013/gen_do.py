"""Generate the ``.do`` file a reader can run in the Stata GUI, from ``specs.py``.

Why generate rather than ship one
---------------------------------
The paper's archive already contains ``czone_analysis_ipw_final.do``, and that file is
what the authors ran.  It is not, however, what this replication runs, for three reasons:

1. It needs ``estout``/``esttab``, which are not installed here and cannot be installed
   without an SSC connection.  Dropping the ``esttab`` lines changes no estimate.
2. It reads ``../dta/...``, so it only works from inside the archive directory as the
   authors laid it out -- which is not where this repository puts the data.
3. Its first-stage tables only exist as printed text, so nothing can be compared
   programmatically.

Generating the do-file from the same :mod:`specs` used by the Python drivers means the
artefact a reader executes and the numbers in the report cannot drift apart.  The file
is written to ``out/adh2013_replication.do`` and is self-contained: an absolute path to
the workfile, one ``regress``/``ivregress`` per replicated column, and a ``log`` that
captures the printed tables.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from adh2013_specs import SPECS  # noqa: E402


HEADER = r"""* ===========================================================================
* Autor, Dorn & Hanson (2013), "The China Syndrome", AER 103(6): 2121-2168.
* Replication of Table 2 (panel I) and Table 3 (panels I and II).
*
* Generated by replication/papers/adh2013/gen_do.py from specs.py -- edit the
* Python description, not this file, or the two will disagree.
*
* Run with:  stata -b do "{do_path}"
* Output:    {log_path}
* ===========================================================================

version 19
clear all
set more off
log using "{log_path}", replace text

* The archive ships the estimation sample already built, which matters: the
* exposure measures involve a 4-digit-SIC concordance of UN Comtrade data to
* County Business Patterns employment, and rebuilding them is a separate
* (much larger) replication.  Table 2 and Table 3 use the built sample.
use "{dta_path}", clear

count
di "estimation sample: " r(N) " observations"
di "Stata version " c(stata_version) " edition " c(flavor)
"""

FOOTER = r"""
log close
"""


def render(do_path: Path, log_path: Path, dta_path: Path) -> str:
    lines: list[str] = [
        HEADER.format(
            do_path=do_path.as_posix(),
            log_path=log_path.as_posix(),
            dta_path=dta_path.as_posix(),
        )
    ]
    current_table = ""
    for spec in SPECS:
        if spec.table != current_table:
            current_table = spec.table
            title = "*" * 75
            lines.append(f"\n{title}\n* {spec.table}\n{title}\n")
        lines.append(f"\n* column ({spec.column}): {spec.label}")
        if spec.notes:
            for note in spec.notes:
                lines.append(f"*   note: {note}")
        if spec.endog:
            # `first` makes Stata print panel II in the same run; the separate
            # regress keeps a machine-readable copy for the comparison, because
            # ivregress leaves the *structural* equation in e(b).
            lines.append(spec.stata_command() + " first")
            lines.append("* the same first stage as its own regression, for capture:")
            lines.append(spec.first_stage_command())
        else:
            lines.append(spec.stata_command())
        lines.append("estimates store " + spec.id.lower())
    lines.append(FOOTER)
    return "\n".join(lines) + "\n"


def main() -> int:
    from adh2013_data import workfile

    out = HERE / "out"
    out.mkdir(parents=True, exist_ok=True)
    do_path = out / "adh2013_replication.do"
    log_path = out / "adh2013_replication.log"
    text = render(do_path, log_path, workfile())
    do_path.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"wrote {do_path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
