def test_var_granger_default_is_the_stata_wald_chi2_not_f():
    """``vargranger`` prints a Wald chi2; the old default returned F.

    StataNow 19.5 on the reference series (``var y1 y2, lags(1)`` /
    ``vargranger``, 2026-10-24, data generated by
    ``retest/domains/tseries/run.py`` with SEED=20261024) reports
    chi2 = 18.10800772465012 (df 1, H0: y2 does not Granger-cause y1) and
    33.61050577858357 (H0: y1 does not).  The F variant is deliberately a
    different statistic and keeps statsmodels' (1, 592) degrees of freedom.
    """

    data, _ = _var1()
    result = VAR(data, lags=1, names=["y1", "y2"]).fit()
    chi2 = result.granger_causality("y1", ["y2"])
    f_test = result.granger_causality("y1", ["y2"], statistic="F")

    assert chi2.method == "Wald"
    assert chi2.df == 1
    assert f_test.method == "F"
    # statsmodels' own F test uses df2 = neqs * (T - k_eq).
    assert f_test.df[0] == 1
    assert f_test.df[1] == 2 * (result.nobs - result.k_per_equation)
    # The Wald statistic is the F statistic times T/(T - k_eq) exactly, because
    # the only difference is Stata's ML residual variance (see VARResults).
    assert chi2.test_statistic == pytest.approx(
        f_test.test_statistic * result.nobs / (result.nobs - result.k_per_equation),
        rel=1e-12,
    )


def test_var_reports_stata_ml_degrees_of_freedom():
    """Stata's ``var`` divides each equation's RSS by T, not by T - k_eq.

    Captured from StataNow 19.5 (``var y1 y2, lags(1)`` on the 300-observation
    reference VAR, 2026-10-24): ``e(N) = 299``, ``k_eq = 3``, and the ratio of
    Stata's standard errors to the unbiased ones is exactly
    ``sqrt((T - k_eq)/T) = 0.9949706303122452``.  ``ml=False`` restores the
    statsmodels/``var, small`` convention on purpose.
    """

    data, _ = _var1()
    result = VAR(data, lags=1, names=["y1", "y2"]).fit()
    small = VAR(data, lags=1, names=["y1", "y2"]).fit(ml=False)

    T = float(result.nobs)
    k_eq = 3
    assert result.k_per_equation == k_eq
    assert result.ml_factor == pytest.approx((T - k_eq) / T, rel=1e-14)
    # bse(frame order) is Stata's equation-by-equation order; compare variances.
    np.testing.assert_allclose(
        result.bse.to_numpy() / small.bse.to_numpy(),
        np.sqrt((T - k_eq) / T),
        rtol=1e-12,
    )
    # e(Sigma) carries the same factor.
    np.testing.assert_allclose(
        result.sigma_u / small._result.sigma_u,
        (T - k_eq) / T,
        rtol=1e-12,
    )


def test_var_ml_false_reproduces_stata_dfk():
    """``fit(ml=False)`` is Stata's ``var ..., dfk``, not an invented option.

    Captured from StataNow 19.5 (2026-10-24) on the ``_var1()`` data below
    (600 observations, seed 7), which is exactly what this test fits:
    ``var y1 y2, lags(1)`` reports ``e(N) = 599`` and
    ``e(Sigma) = [0.8549362620862754, 0.024724690652668715,
    0.024724690652668715, 0.9410628252673956]``; adding ``dfk`` gives
    ``[0.8592396325330185, 0.024849143793537854, 0.024849143793537854,
    0.9457997186831711]``.  The point estimates are identical; only the divisor
    changes (1/T vs 1/(T - k_eq), k_eq = 3).
    """

    data, _ = _var1()
    stata_ml = np.array([
        0.8549362620862754, 0.024724690652668715,
        0.024724690652668715, 0.9410628252673956,
    ])
    stata_dfk = np.array([
        0.8592396325330185, 0.024849143793537854,
        0.024849143793537854, 0.9457997186831711,
    ])
    stata_dfk_se = np.array([
        0.03558034016744094, 0.034030307894141784, 0.03895626026325347,
        0.0373295311873237, 0.035703296648385036, 0.040871417350004824,
    ])

    default = VAR(data, lags=1, names=["y1", "y2"]).fit()
    dfk = VAR(data, lags=1, names=["y1", "y2"]).fit(ml=False)

    assert default.nobs == 599
    assert default.k_per_equation == 3
    np.testing.assert_allclose(default.sigma_u.ravel(), stata_ml, rtol=1e-13)
    np.testing.assert_allclose(dfk.sigma_u.ravel(), stata_dfk, rtol=1e-13)
    np.testing.assert_allclose(dfk.bse.to_numpy(), stata_dfk_se, rtol=1e-13)
    # dfk changes only the residual-covariance divisor, never the coefficients.
    np.testing.assert_allclose(
        dfk.stata_params().to_numpy(), default.stata_params().to_numpy(), rtol=0
    )


