def test_adf_printed_critical_values_follow_dfuller_ado_table():
    """Stata's printed 1%/5%/10% ADF values are NOT MacKinnon response-surface values.

    Captured from StataNow 19.5 (``dfuller y_rw, lags(2)`` / ``lags(2) trend`` on
    the 300-observation reference random walk, 2026-10-24): r(N) = 297 and the
    printed values are (-3.45624, -2.87812, -2.57) for the constant case and
    (-3.98812, -3.42812, -3.13) with a trend.  ``dfuller.ado``'s ``GetCrit``
    hard-codes a six-point table and interpolates linearly in N; statsmodels'
    MacKinnon values are -3.45256/-2.87132/-2.57198, i.e. 2.4e-3 away.
    """

    rng = np.random.default_rng(21)
    walk = np.cumsum(rng.normal(size=300))

    constant = unitroot(walk, test="adf", regression="c", maxlag=2, autolag=None)
    assert constant.observations == 297
    assert constant.critical["1%"] == pytest.approx(-3.45624, abs=1e-12)
    assert constant.critical["5%"] == pytest.approx(-2.87812, abs=1e-12)
    assert constant.critical["10%"] == pytest.approx(-2.57, abs=1e-12)

    with_trend = unitroot(walk, test="adf", regression="ct", maxlag=2, autolag=None)
    assert with_trend.critical["1%"] == pytest.approx(-3.98812, abs=1e-12)
    assert with_trend.critical["5%"] == pytest.approx(-3.42812, abs=1e-12)

    # The p-value is still MacKinnon's, and the statistic must not move.
    from statsmodels.tsa.stattools import adfuller

    reference = adfuller(walk, maxlag=2, regression="c", autolag=None, result_object=True)
    assert constant.statistic == pytest.approx(float(reference.statistic), rel=1e-12)
    assert constant.pvalue == pytest.approx(float(reference.pvalue), rel=1e-12)


def test_adf_critical_values_interpolate_like_the_ado():
    """The table is piecewise linear in N, so 295 and 299 differ in the 4th decimal.

    StataNow 19.5, 2026-10-24: ``dfuller y_rw, lags(0)`` (N = 299) prints
    -3.45608 and ``dfuller y_ar, lags(4)`` (N = 295) prints -3.4564 -- the same
    linear segment 250..500, evaluated at two points.
    """

    rng = np.random.default_rng(23)
    walk = np.cumsum(rng.normal(size=300))
    n299 = unitroot(walk, test="adf", regression="c", maxlag=0, autolag=None)
    n295 = unitroot(walk, test="adf", regression="c", maxlag=4, autolag=None)
    assert n299.observations == 299
    assert n295.observations == 295
    assert n299.critical["1%"] == pytest.approx(-3.45608, abs=1e-12)
    assert n295.critical["1%"] == pytest.approx(-3.4564, abs=1e-12)


def test_arima_reports_statas_estimation_sample_size():
    """``e(N)`` counts the estimation sample: 299 for d=1 on 300 observations.

    StataNow 19.5 (``arima y_rw, arima(0,1,1)``, 2026-10-24) reports
    ``e(N) = 299`` and uses that value in its ``estat ic`` BIC penalty;
    ``arima y_s, arima(1,0,0) sarima(0,1,1,4)`` reports 296 of 300 (one seasonal
    difference of order 4).  ``res.nobs`` stays the residual length, because
    StataResults requires it.
    """

    walk = np.cumsum(np.random.default_rng(29).normal(size=300))
    result = ARIMA(walk, order=(0, 1, 1), trend="t").fit()
    assert result.e["N"] == 299
    assert int(result.nobs) == 300
    assert result.df_resid == 299.0

    seasonal = _ar1(n=300, phi=0.5)
    seasonal = seasonal + 0.4 * np.roll(seasonal, 4)
    sarima = ARIMA(seasonal, order=(1, 0, 0), seasonal_order=(0, 1, 1, 4),
                   trend="t").fit()
    assert sarima.e["N"] == 296
    assert int(sarima.nobs) == 300

    stationary = ARIMA(_ar1(), order=(1, 0, 0)).fit()
    assert stationary.e["N"] == len(stationary.resid)


def test_kpss_has_the_opposite_null():
    rng = np.random.default_rng(17)
    walk = np.cumsum(rng.normal(size=400))
    outcome = unitroot(walk, test="kpss")
    # KPSS's null is stationarity, so a random walk should reject it.
    assert outcome.pvalue < 0.05
    assert "stationary" in outcome.null


def test_pp_runs():
    rng = np.random.default_rng(19)
    walk = np.cumsum(rng.normal(size=300))
    outcome = unitroot(walk, test="pp")
    assert np.isfinite(outcome.statistic)
    assert 0.0 <= outcome.pvalue <= 1.0


