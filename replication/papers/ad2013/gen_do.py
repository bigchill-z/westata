"""Render the replicated specifications into a ``.do`` file a reader can run in Stata.

The authors' own ``czone_analysis.do`` is in the archive, but it depends on ``xi`` and on
their directory layout, and its output goes to a log a reader would have to diff.  This
generated file is self-contained: an absolute path to the workfile, one ``regress`` per
replicated row, and a log.  It is generated from ``specs.py`` so the human-runnable
artefact and the compared numbers cannot diverge.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from ad2013_specs import SPECS  # noqa: E402

HEADER = r"""* ===========================================================================
* Autor & Dorn (2013), "The Growth of Low-Skill Service Jobs and the
* Polarization of the U.S. Labor Market", AER 103(5): 1553-1597.
*
* Replication of Table 3 (routine-task intensity) and Table 4
* (low-skill service employment).
*
* GENERATED by gen_do.py from specs.py -- edit the Python description, not
* this file, or the two will disagree.
*
* Run with:  stata -b do "{do_path}"
* Output:    {log_path}
* ===========================================================================

version 19
clear all
set more off
log using "{log_path}", replace text

use "{dta_path}", clear
count
di "estimation sample: " r(N) " observations"
di "Stata version " c(stata_version)
"""

FOOTER = """
log close
"""


def render(do_path: Path, log_path: Path, dta_path: Path) -> str:
    lines = [HEADER.format(do_path=do_path.as_posix(), log_path=log_path.as_posix(),
                           dta_path=dta_path.as_posix())]
    current = ""
    for spec in SPECS:
        if spec.table != current:
            current = spec.table
            lines.append(f"\n{'*' * 75}\n* {spec.table}\n{'*' * 75}\n")
        lines.append(f"\n* row {spec.row}: {spec.label}")
        lines.append(spec.stata_command())
        lines.append(f"estimates store {spec.id.lower()}")
    lines.append(FOOTER)
    return "\n".join(lines) + "\n"


def main() -> int:
    from ad2013_acquire import workfile

    out = HERE / "out"
    out.mkdir(parents=True, exist_ok=True)
    do_path = out / "ad2013_replication.do"
    log_path = out / "ad2013_replication.log"
    text = render(do_path, log_path, workfile())
    do_path.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"wrote {do_path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
