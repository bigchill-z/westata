def controls(*groups: tuple[str, ...]) -> tuple[str, ...]:
    """Flatten control groups, preserving the paper's left-to-right order.

    Order matters for a human reading the generated do-file, and it matters for the
    report: a coefficient vector that matches in value but not in order would still
    align under name matching, but the do-file would no longer look like the paper's.
    """

    out: list[str] = []
    for group in groups:
        for name in group:
            if name not in out:
                out.append(name)
    return tuple(out)


@dataclass(frozen=True)
class Spec:
    """One estimated model.

    ``condition`` is written in syntax that pandas and Stata both accept (``yr==1990``)
    so the same string restricts both samples.  Keeping one string rather than two is
    what stops the samples from diverging.
    """

    id: str
    table: str
    column: int
    depvar: str
    endog: str | None = None
    instruments: tuple[str, ...] = ()
    exog: tuple[str, ...] = ()
    weight_var: str | None = None
    weight_type: str | None = None
    cluster: str | None = None
    condition: str | None = None
    label: str = ""
    notes: tuple[str, ...] = field(default_factory=tuple)

    # -- rendering ---------------------------------------------------------
    def stata_command(self) -> str:
        """The Stata command line, assembled exactly as the paper's do-file writes it."""

        parts: list[str] = []
        if self.endog:
            parts.append("ivregress 2sls")
            parts.append(self.depvar)
            parts.append(f"({self.endog}=" + " ".join(self.instruments) + ")")
        else:
            parts.append("regress")
            parts.append(self.depvar)
        parts.extend(self.exog)
        if self.weight_var:
            parts.append(f"[{self.weight_abbrev}={self.weight_var}]")
        if self.condition:
            parts.append(f"if {self.condition}")
        if self.cluster:
            parts.append(f", cluster({self.cluster})")
        return " ".join(parts)

    @property
    def weight_abbrev(self) -> str:
        return {"aweight": "aw", "pweight": "pw", "fweight": "fw", "iweight": "iw"}[
            self.weight_type or ""
        ]

    @property
    def formula(self) -> str:
        """The ``westata``/patsy formula for the same model (no weights, no subset)."""

        rhs = list(self.exog)
        if self.endog:
            rhs.append(f"[{self.endog} ~ " + " + ".join(self.instruments) + "]")
        return f"{self.depvar} ~ " + " + ".join(rhs)

    @property
    def terms_of_record(self) -> tuple[str, ...]:
        """The coefficients the paper prints in this column (beyond the controls)."""

        if self.endog:
            return (self.endog,) + self.instruments
        return (self.depvar,)  # replaced by the first regressor below

    def first_stage_command(self) -> str:
        """The first stage of the 2SLS model, written as a separate OLS regression.

        Stata's ``ivregress ..., first`` prints this table itself, but the printed
        values are not reachable through ``e(b)`` (that holds the structural equation),
        so the replication runs the first stage as its own ``regress`` command.  The
        two are the same regression; see the note in ``REPORT.md`` about the first
        stage standard error, which is the one row where Stata's own convention has
        changed between versions.
        """

        parts = ["regress", self.endog or "", *self.exog, *self.instruments]
        if self.weight_var:
            parts.append(f"[{self.weight_abbrev}={self.weight_var}]")
        if self.condition:
            parts.append(f"if {self.condition}")
        if self.cluster:
            parts.append(f", cluster({self.cluster})")
        return " ".join(p for p in parts if p)


